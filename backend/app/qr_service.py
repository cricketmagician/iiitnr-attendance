"""Dynamic 3-Second Rotating QR Code Service for Guard / Kiosk.

The Guard screen displays a dynamic QR code that rotates every 3 seconds.
Students scan this QR code with their mobile phone right before capturing
their selfie. This guarantees physical proximity at the gate/department,
preventing any proxy attendance via forwarded photos or remote marking.
"""
import hashlib
import hmac
import time
from typing import Tuple, Dict, Any
from app.config import get_settings


ROTATION_INTERVAL_SECONDS = 3
# Allow up to 15 seconds (5 slots) for scanning, front-camera selfie capture, and tapping Confirm
MAX_TOLERANCE_SECONDS = 15


def generate_guard_qr(session: str) -> Dict[str, Any]:
    """Generates the dynamic rotating QR payload for the guard screen.
    Rotates every 3 seconds."""
    now = int(time.time())
    slot = now // ROTATION_INTERVAL_SECONDS
    seconds_remaining = ROTATION_INTERVAL_SECONDS - (now % ROTATION_INTERVAL_SECONDS)
    
    secret = get_settings().jwt_secret
    msg = f"IIITNR-ATT:{session}:{slot}".encode("utf-8")
    sig = hmac.new(secret.encode("utf-8"), msg, hashlib.sha256).hexdigest()[:16]
    
    qr_payload = f"IIITNR-ATT:{session}:{slot}:{sig}"
    
    return {
        "qr_string": qr_payload,
        "session": session,
        "slot": slot,
        "seconds_remaining": seconds_remaining,
        "rotation_interval": ROTATION_INTERVAL_SECONDS,
        "timestamp": now,
    }


def verify_guard_qr(qr_string: str, expected_session: str, max_drift_seconds: int = MAX_TOLERANCE_SECONDS) -> Tuple[bool, str]:
    """Verifies that the scanned QR code was legitimately generated by the Guard Screen
    and is within the allowed rotation freshness window."""
    if not qr_string or not qr_string.startswith("IIITNR-ATT:"):
        return False, "Invalid QR code format. Please scan the official IIITNR Guard QR."

    parts = qr_string.split(":")
    if len(parts) != 4:
        return False, "Malformed QR code."

    _, session, slot_str, sig = parts

    def _norm(s: str) -> str:
        s = str(s).strip().lower()
        if s.startswith("m"):
            return "morning"
        if s.startswith("e"):
            return "evening"
        return s

    # Check session match if expected_session is provided
    if expected_session and _norm(session) != _norm(expected_session):
        return False, f"QR code is for {session} session, but current session is {expected_session}."

    try:
        slot = int(slot_str)
    except ValueError:
        return False, "Invalid slot in QR code."

    # Verify HMAC signature
    secret = get_settings().jwt_secret
    msg = f"IIITNR-ATT:{session}:{slot}".encode("utf-8")
    expected_sig = hmac.new(secret.encode("utf-8"), msg, hashlib.sha256).hexdigest()[:16]

    if not hmac.compare_digest(sig, expected_sig):
        return False, "Counterfeit or unauthorized Guard QR code."

    # Check expiration / freshness
    now = int(time.time())
    current_slot = now // ROTATION_INTERVAL_SECONDS
    slot_drift = abs(current_slot - slot)
    max_slots = max(1, max_drift_seconds // ROTATION_INTERVAL_SECONDS)

    if slot_drift > max_slots:
        return False, "Guard QR Code expired (rotates every 3s). Please scan the live QR code again."

    return True, "Valid Guard QR code."
